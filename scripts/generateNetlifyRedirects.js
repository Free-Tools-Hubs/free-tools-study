/**
 * StudyToolsHub — Netlify Redirect & Routing Architecture Generator
 *
 * Deterministically generates `public/_redirects` from the authoritative
 * `src/data/legacyTopicUrlManifest.json` and `src/data/canonicalStudyTopics.json`.
 *
 * Rule Hierarchy:
 * 1. Specific approved legacy redirects (HTTP 301)
 * 2. Specific approved permanently obsolete URLs (HTTP 410 Gone)
 * 3. Explicit valid canonical application routes (HTTP 200 Rewrite to /index.html)
 * 4. Deliberate final fallback for unknown and missing URLs (HTTP 404)
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '..');

const MANIFEST_PATH = path.join(REPO_ROOT, 'src', 'data', 'legacyTopicUrlManifest.json');
const CANONICAL_PATH = path.join(REPO_ROOT, 'src', 'data', 'canonicalStudyTopics.json');
const REDIRECTS_OUT_PATH = path.join(REPO_ROOT, 'public', '_redirects');
const DIST_REDIRECTS_PATH = path.join(REPO_ROOT, 'dist', '_redirects');

/**
 * Normalizes a URL path for Netlify _redirects.
 * Ensures leading slash, removes trailing whitespace, and encodes spaces as %20.
 */
export function normalizeRedirectPath(rawPath) {
  if (!rawPath) return '';
  const trimmed = String(rawPath).trim();
  const withLeadingSlash = trimmed.startsWith('/') ? trimmed : `/${trimmed}`;
  // Netlify requires special characters and spaces in redirect paths to be URL-encoded
  return withLeadingSlash.replace(/\s+/g, '%20');
}

export function generateNetlifyRedirects() {
  if (!fs.existsSync(MANIFEST_PATH)) {
    throw new Error(`Authoritative manifest not found at: ${MANIFEST_PATH}`);
  }
  if (!fs.existsSync(CANONICAL_PATH)) {
    throw new Error(`Canonical dataset not found at: ${CANONICAL_PATH}`);
  }

  const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
  const canonicalTopics = JSON.parse(fs.readFileSync(CANONICAL_PATH, 'utf8'));
  const canonicalSlugMap = new Map(canonicalTopics.map(t => [t.slug, t]));

  const lines = [
    '# =============================================================================',
    '# StudyToolsHub — Netlify Redirect & Routing Configuration',
    '# Deterministically generated by scripts/generateNetlifyRedirects.js',
    `# Generated from manifest schema v${manifest.schemaVersion} (${canonicalTopics.length} canonical topics)`,
    '# =============================================================================',
    '',
    '# -----------------------------------------------------------------------------',
    '# SECTION 1: Approved Canonical Legacy Redirects (HTTP 301)',
    '# Preserves genuine educational equivalent links from legacy URLs to canonical topics.',
    '# -----------------------------------------------------------------------------'
  ];

  const seenSourcePaths = new Set();
  const redirectRules = [];
  const obsoleteRules = [];
  const manualReviewPaths = [];
  let selfRedirectsSkipped = 0;

  // Process manifest records
  for (const record of manifest.records) {
    const rawFlashcardUrl = record.flashcardUrl;
    const rawQuizUrl = record.quizUrl;
    const disposition = record.disposition;

    if (disposition === 'redirect') {
      const canonicalSlug = record.canonicalSlug;
      if (!canonicalSlug || !canonicalSlugMap.has(canonicalSlug)) {
        throw new Error(
          `Manifest redirect record ${record.legacyRecordId} references non-existent canonical slug "${canonicalSlug}"!`
        );
      }

      const canonicalFlashcardDest = `/${canonicalSlug}`;
      const canonicalQuizDest = `/quiz/${canonicalSlug}`;

      // Flashcard 301 rule
      const normFcSource = normalizeRedirectPath(rawFlashcardUrl);
      if (normFcSource === canonicalFlashcardDest) {
        selfRedirectsSkipped++;
      } else {
        if (seenSourcePaths.has(normFcSource)) {
          throw new Error(`Duplicate source path detected in redirect rules: ${normFcSource}`);
        }
        seenSourcePaths.add(normFcSource);
        redirectRules.push(`${normFcSource}  ${canonicalFlashcardDest}  301`);
      }

      // Quiz 301 rule
      const normQzSource = normalizeRedirectPath(rawQuizUrl);
      if (normQzSource === canonicalQuizDest) {
        selfRedirectsSkipped++;
      } else {
        if (seenSourcePaths.has(normQzSource)) {
          throw new Error(`Duplicate source path detected in redirect rules: ${normQzSource}`);
        }
        seenSourcePaths.add(normQzSource);
        redirectRules.push(`${normQzSource}  ${canonicalQuizDest}  301`);
      }
    } else if (disposition === 'obsolete') {
      // Flashcard 410 rule
      const normFcSource = normalizeRedirectPath(rawFlashcardUrl);
      if (seenSourcePaths.has(normFcSource)) {
        throw new Error(`Duplicate source path detected in obsolete rules: ${normFcSource}`);
      }
      seenSourcePaths.add(normFcSource);
      obsoleteRules.push(`${normFcSource}  /410.html  410`);

      // Quiz 410 rule
      const normQzSource = normalizeRedirectPath(rawQuizUrl);
      if (seenSourcePaths.has(normQzSource)) {
        throw new Error(`Duplicate source path detected in obsolete rules: ${normQzSource}`);
      }
      seenSourcePaths.add(normQzSource);
      obsoleteRules.push(`${normQzSource}  /410.html  410`);
    } else if (disposition === 'manual_review') {
      // Manual review paths are explicitly excluded from automatic 301 or 410 rules
      manualReviewPaths.push({
        recordId: record.legacyRecordId,
        legacySlug: record.legacySlug,
        flashcardUrl: rawFlashcardUrl,
        quizUrl: rawQuizUrl,
        canonicalSlug: record.canonicalSlug,
        reason: record.reason,
        reviewStatus: record.reviewStatus
      });
    } else {
      throw new Error(`Unknown disposition "${disposition}" on record ${record.legacyRecordId}`);
    }
  }

  // Handle nonDatasetNavigationUrls
  for (const nav of manifest.nonDatasetNavigationUrls) {
    if (nav.disposition === 'redirect') {
      const normFc = normalizeRedirectPath(nav.flashcardUrl);
      const targetFc = `/${nav.canonicalSlug}`;
      if (normFc === targetFc) {
        selfRedirectsSkipped++;
      } else if (!seenSourcePaths.has(normFc)) {
        seenSourcePaths.add(normFc);
        redirectRules.push(`${normFc}  ${targetFc}  301`);
      }

      const normQz = normalizeRedirectPath(nav.quizUrl);
      const targetQz = `/quiz/${nav.canonicalSlug}`;
      if (normQz === targetQz) {
        selfRedirectsSkipped++;
      } else if (!seenSourcePaths.has(normQz)) {
        seenSourcePaths.add(normQz);
        redirectRules.push(`${normQz}  ${targetQz}  301`);
      }
    } else if (nav.disposition === 'manual_review') {
      manualReviewPaths.push({
        recordId: 'nav-hardcoded',
        legacySlug: nav.legacySlug,
        flashcardUrl: nav.flashcardUrl,
        quizUrl: nav.quizUrl,
        canonicalSlug: nav.canonicalSlug,
        reason: nav.reason,
        reviewStatus: nav.reviewStatus
      });
    }
  }

  lines.push(...redirectRules);
  lines.push('');
  lines.push('# -----------------------------------------------------------------------------');
  lines.push('# SECTION 2: Confirmed Permanently Removed Resources (HTTP 410 Gone)');
  lines.push('# Permanently removes synthetic variations, duplicate repeats, and invalid level pairings.');
  lines.push('# -----------------------------------------------------------------------------');
  lines.push(...obsoleteRules);
  lines.push('');

  lines.push('# -----------------------------------------------------------------------------');
  lines.push('# SECTION 3: Explicit Valid Canonical Application Routes (HTTP 200 Rewrite)');
  lines.push('# Serves index.html for known canonical routes, enabling client-side hydration & deep linking.');
  lines.push('# -----------------------------------------------------------------------------');

  // Static routes
  const staticRoutes = [
    '/about',
    '/contact',
    '/privacy-policy',
    '/terms-of-service',
    '/study-timetable-template'
  ];
  for (const r of staticRoutes) {
    lines.push(`${r}  /index.html  200`);
  }
  lines.push('/planner/:examType  /index.html  200');

  // Canonical flashcard and quiz routes
  lines.push('# Canonical Flashcard Topic Routes');
  for (const t of canonicalTopics) {
    lines.push(`/${t.slug}  /index.html  200`);
  }

  lines.push('# Canonical Quiz Topic Routes');
  for (const t of canonicalTopics) {
    lines.push(`/quiz/${t.slug}  /index.html  200`);
  }

  lines.push('');
  lines.push('# -----------------------------------------------------------------------------');
  lines.push('# SECTION 4: Deliberate Final Fallback for Unknown & Missing URLs (HTTP 404)');
  lines.push('# Eliminates Soft-404: Unknown paths never silently return HTTP 200.');
  lines.push('# -----------------------------------------------------------------------------');
  lines.push('/*  /404.html  404');
  lines.push('');

  const outputContent = lines.join('\n');
  fs.writeFileSync(REDIRECTS_OUT_PATH, outputContent, 'utf8');

  // If dist/ directory exists, synchronize it as well
  if (fs.existsSync(path.dirname(DIST_REDIRECTS_PATH))) {
    fs.writeFileSync(DIST_REDIRECTS_PATH, outputContent, 'utf8');
  }

  // Ensure public/404.html and public/410.html are in dist if dist exists
  const dist404 = path.join(REPO_ROOT, 'dist', '404.html');
  const dist410 = path.join(REPO_ROOT, 'dist', '410.html');
  const pub404 = path.join(REPO_ROOT, 'public', '404.html');
  const pub410 = path.join(REPO_ROOT, 'public', '410.html');

  if (fs.existsSync(path.join(REPO_ROOT, 'dist'))) {
    if (fs.existsSync(pub404)) fs.copyFileSync(pub404, dist404);
    if (fs.existsSync(pub410)) fs.copyFileSync(pub410, dist410);
  }

  const resultStats = {
    totalRedirectRules: redirectRules.length,
    totalObsoleteRules: obsoleteRules.length,
    totalCanonical200Rules: staticRoutes.length + 1 + (canonicalTopics.length * 2),
    totalManualReviewExclusions: manualReviewPaths.length,
    totalRulesWritten: redirectRules.length + obsoleteRules.length + staticRoutes.length + 1 + (canonicalTopics.length * 2) + 1,
    selfRedirectsSkipped,
    redirectsFileSize: fs.statSync(REDIRECTS_OUT_PATH).size,
    manualReviewRecords: manualReviewPaths
  };

  return resultStats;
}

function main() {
  console.log('=== GENERATING NETLIFY REDIRECTS ===');
  const stats = generateNetlifyRedirects();
  console.log(`Generated ${stats.totalRulesWritten.toLocaleString()} total rules -> ${REDIRECTS_OUT_PATH} (${stats.redirectsFileSize.toLocaleString()} bytes)`);
  console.log(`  - 301 Permanent Redirects: ${stats.totalRedirectRules.toLocaleString()} rules`);
  console.log(`  - 410 Permanently Gone:    ${stats.totalObsoleteRules.toLocaleString()} rules`);
  console.log(`  - 200 Canonical Rewrites:   ${stats.totalCanonical200Rules.toLocaleString()} rules`);
  console.log(`  - 404 Fallback Rule:        1 rule (/* -> /404.html 404)`);
  console.log(`  - Manual Review Exclusions: ${stats.totalManualReviewExclusions.toLocaleString()} records (0 automatic rules generated)`);
  console.log(`  - Self-Redirects Prevented: ${stats.selfRedirectsSkipped} loops skipped`);
  console.log('=== GENERATION SUCCESSFUL ===\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) {
  main();
}

